import { describe, expect, it } from 'vitest'
import { detectLanguage } from '../archive/classify'
import type { ArchiveEntry } from '../archive/guard'
import { generatedSkipReason, splitGeneratedEntries } from './generated'

function entry(name: string, text = 'const a = 1\n'): ArchiveEntry {
  const detection = detectLanguage(name, text)
  return { name, text, language: detection.language, languageSource: detection.source, encoding: 'utf-8', bytes: text.length }
}

const LOCKFILES = [
  'package-lock.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'poetry.lock',
  'Cargo.lock',
  'go.sum',
  'composer.lock',
  'Gemfile.lock',
]

const GENERATED_FOLDERS = [
  '.git',
  'node_modules',
  'dist',
  'build',
  '.next',
  'coverage',
  '__pycache__',
  '.venv',
  'venv',
  'vendor',
  'target',
  'bin',
  'obj',
  '.idea',
  '.vscode',
  '.gradle',
  '.terraform',
]

describe('generated and vendored detection', () => {
  it('names the reason for every default heuristic', () => {
    expect(generatedSkipReason('assets/app.min.js', 'var a=1\n')?.detail).toMatch(/minified/i)
    expect(generatedSkipReason('styles/site.min.css', 'a{b:c}\n')?.detail).toMatch(/minified/i)
    expect(generatedSkipReason('maps/app.js.map', '{"version":3}\n')?.detail).toMatch(/source map/i)
    for (const name of LOCKFILES) {
      expect(generatedSkipReason(name, '')?.detail, name).toMatch(/lockfile/i)
    }
    for (const folder of GENERATED_FOLDERS) {
      expect(generatedSkipReason(`${folder}/src/app.js`, 'const a = 1\n')?.detail, folder).toContain(folder)
    }
    expect(generatedSkipReason('src/app.js', '// Code generated by protoc. DO NOT EDIT.\nconst a = 1\n')?.detail).toMatch(/marker/i)
    expect(generatedSkipReason('src/app.js', '/* @generated */\nconst a = 1\n')?.detail).toMatch(/marker/i)
    expect(generatedSkipReason('src/app.js', '// auto-generated file\nconst a = 1\n')?.detail).toMatch(/marker/i)
    expect(generatedSkipReason('bundle.js', `const a = ${'x'.repeat(20_001)}\n`)?.detail).toMatch(/long single line/i)
    expect(generatedSkipReason('src/app.js', 'const a = 1\n')).toBeNull()
  })

  it('keeps ordinary source and a generated marker far down the file', () => {
    expect(generatedSkipReason('src/app.ts', 'export const a = 1\n')).toBeNull()
    const late = `${'const a = 1\n'.repeat(10)}// Code generated\n`
    expect(generatedSkipReason('src/app.ts', late)).toBeNull()
  })

  it('splits entries into analysed and skipped with a message that names the override', () => {
    const kept = entry('src/app.py', 'print(1)\n')
    const minified = entry('dist/app.min.js', 'var a=1\n')
    const lock = entry('package-lock.json', '{"lockfileVersion":3}\n')
    const split = splitGeneratedEntries([kept, minified, lock], false)

    expect(split.kept.map((item) => item.name)).toEqual(['src/app.py'])
    expect(split.skipped.map((item) => [item.name, item.code])).toEqual([
      ['dist/app.min.js', 'generated_file'],
      ['package-lock.json', 'generated_file'],
    ])
    expect(split.skipped[0]?.message).toMatch(/Include generated and vendored files/)
  })

  it('overrides every heuristic except .git when the user asks for generated files', () => {
    const entries = [
      entry('src/app.js'),
      entry('dist/app.min.js', 'var a=1\n'),
      entry('package-lock.json', '{"lockfileVersion":3}\n'),
      entry('node_modules/leftpad/index.js', 'module.exports = 1\n'),
      entry('.idea/workspace.xml', '<project/>\n'),
      entry('.git/config', '[core]\n'),
    ]
    const split = splitGeneratedEntries(entries, true)

    expect(split.kept.map((item) => item.name)).toEqual([
      'src/app.js',
      'dist/app.min.js',
      'package-lock.json',
      'node_modules/leftpad/index.js',
      '.idea/workspace.xml',
    ])
    expect(split.skipped.map((item) => [item.name, item.code])).toEqual([['.git/config', 'generated_file']])
  })
})
